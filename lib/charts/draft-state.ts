// PostgreSQL JSONB and browser objects can have different key order.
// Compare values, keeping array order and explicit empty values meaningful.
export function draftFingerprint(value: unknown): string {
  return JSON.stringify(value, (_key, item) =>
    item && typeof item === "object" && !Array.isArray(item)
      ? Object.fromEntries(
          Object.keys(item)
            .sort()
            .map((key) => [key, item[key]]),
        )
      : item,
  );
}
